/** ё and е are the same letter for our purposes, and case never matters. */
const normalise = (word) => String(word || '').trim().toLowerCase().replace(/ё/g, 'е');

const RUSSIAN_ONLY = /^[а-я]+$/;

/** Split a blob of whitespace-separated words into a clean, checked set. */
function parseWords(text) {
  const words = new Set();
  for (const raw of String(text).split(/\s+/)) {
    const word = normalise(raw);
    // Two letters is the shortest a Балда word can be, and anything with a character
    // outside the alphabet is a typo rather than a word.
    if (word.length < 2 || !RUSSIAN_ONLY.test(word)) continue;
    words.add(word);
  }
  return words;
}

let cached = null;

/**
 * The dictionary.
 *
 * The built-in list, plus `data/balda-ru.txt` if the operator has supplied one. The file
 * is read once and merged rather than replacing the built-in list, so a short extra file
 * adds words instead of silently removing thousands.
 */
function loadWords(dataDir) {
  if (cached) return cached;
  const words = parseWords(BUILT_IN);
  if (dataDir) {
    try {
      // Required lazily so this module stays usable where there is no filesystem.
      const fs = require('node:fs');
      const path = require('node:path');
      const file = path.join(dataDir, 'balda-ru.txt');
      if (fs.existsSync(file)) {
        for (const word of parseWords(fs.readFileSync(file, 'utf8'))) words.add(word);
      }
    } catch { /* no extra dictionary; the built-in list stands alone */ }
  }
  cached = words;
  return words;
}

/** Forget the cache. Tests need this; nothing else should. */
const resetCache = () => { cached = null; };

/** Every word of a given length, for picking an opening row. */
const wordsOfLength = (words, n) => [...words].filter((w) => w.length === n);

module.exports = { BUILT_IN, normalise, parseWords, loadWords, resetCache, wordsOfLength };
